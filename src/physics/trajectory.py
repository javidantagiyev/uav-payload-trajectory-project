"""Trajectory recording using the repository's canonical ODE step functions."""

from dataclasses import dataclass
from typing import Callable
import numpy as np

from .integrators import euler_step, rk4_step


@dataclass(frozen=True)
class Trajectory:
    times: np.ndarray
    states: np.ndarray

    @property
    def positions(self) -> np.ndarray:
        return self.states[:, :3]

    @property
    def velocities(self) -> np.ndarray:
        return self.states[:, 3:]


def integrate(rhs: Callable, state0, duration_s: float, max_step_s: float, method: str = "rk4") -> Trajectory:
    """Integrate for a fixed time interval with stored states; no event detection."""
    if not np.isfinite(duration_s) or duration_s <= 0:
        raise ValueError("duration_s must be positive and finite")
    if not np.isfinite(max_step_s) or max_step_s <= 0:
        raise ValueError("max_step_s must be positive and finite")
    if method not in {"euler", "rk4"}:
        raise ValueError("method must be 'euler' or 'rk4'")
    initial = np.asarray(state0, dtype=float)
    if initial.shape != (6,) or not np.all(np.isfinite(initial)):
        raise ValueError("state0 must contain six finite components")
    count = int(np.ceil(duration_s / max_step_s))
    if count > 5_000_000:
        raise ValueError("too many integration steps")
    times = np.linspace(0.0, duration_s, count + 1)
    states = np.empty((count + 1, 6), dtype=float)
    states[0] = initial
    step = euler_step if method == "euler" else rk4_step

    for i in range(count):
        dt = float(times[i + 1] - times[i])
        # Both the existing single-step integrators and dynamics RHS accept sequences.
        next_state = step(rhs, float(times[i]), tuple(states[i]), dt)
        states[i + 1] = next_state
        if not np.all(np.isfinite(states[i + 1])):
            raise FloatingPointError("nonfinite state generated by numerical integration")
    return Trajectory(times, states)
